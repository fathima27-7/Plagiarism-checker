class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that automatically computes the total page count
    and renders dynamic running headers and 'Page X of Y' footers on every page.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#64748b'))

        # Running header on pages 2+
        if self._pageNumber > 1:
            self.setStrokeColor(colors.HexColor('#cbd5e1'))
            self.setLineWidth(0.5)
            self.line(36, 756, 576, 756)
            self.drawString(36, 762, "PlagiScan AI — Academic Content Integrity & Stylometric Evaluation")

        # Running footer on every page
        self.setStrokeColor(colors.HexColor('#cbd5e1'))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45)
        self.drawString(36, 32, "Confidential Academic Evaluation • Generated by PlagiScan AI")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(576, 32, page_str)

        self.restoreState()


class PDFReportGenerator:
    @staticmethod
    def generate_pdf(analysis, document, matches=None, ai_sentences=None, sections=None, suggestions=None):
        """
        Builds a comprehensive academic evaluation report adhering to professional standards.
        The database analysis record is the single source of truth (no recalculation or artificial capping).
        """
        matches = matches or []
        ai_sentences = ai_sentences or []
        sections = sections or []
        suggestions = suggestions or []

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=40,
            bottomMargin=52
        )

        styles = getSampleStyleSheet()

        # Color Palette
        PRIMARY_COLOR = colors.HexColor('#1e293b')   # Slate 900
        ACCENT_COLOR = colors.HexColor('#2563eb')    # Blue 600
        MUTED_TEXT = colors.HexColor('#64748b')      # Slate 500
        LIGHT_BG = colors.HexColor('#f8fafc')        # Slate 50
        BORDER_COLOR = colors.HexColor('#cbd5e1')    # Slate 300
        YELLOW_HIGHLIGHT = "#fef08a"                # Yellow highlighter

        # Typography
        h1_style = ParagraphStyle(
            'H1',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=18,
            leading=22,
            textColor=ACCENT_COLOR
        )
        h2_style = ParagraphStyle(
            'H2',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=12,
            leading=16,
            textColor=PRIMARY_COLOR,
            spaceBefore=10,
            spaceAfter=5
        )
        h3_style = ParagraphStyle(
            'H3',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=10,
            leading=13,
            textColor=PRIMARY_COLOR,
            spaceBefore=6,
            spaceAfter=2
        )
        subtitle_style = ParagraphStyle(
            'Sub',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9.5,
            leading=13,
            textColor=MUTED_TEXT
        )
        body_style = ParagraphStyle(
            'Body',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=12,
            textColor=colors.HexColor('#334155')
        )
        body_bold = ParagraphStyle(
            'BodyBold',
            parent=body_style,
            fontName='Helvetica-Bold'
        )
        card_val_style = ParagraphStyle(
            'CardVal',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=18,
            leading=22,
            alignment=1
        )
        card_lbl_style = ParagraphStyle(
            'CardLbl',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=8,
            leading=11,
            alignment=1,
            textColor=MUTED_TEXT
        )
        bullet_style = ParagraphStyle(
            'Bullet',
            parent=body_style,
            leftIndent=15,
            spaceAfter=2
        )

        elements = []

        # =========================================================================
        # PAGE 1: HEADER, METADATA, SCORECARDS, AND EXECUTIVE SUMMARY
        # =========================================================================

        # 1.1 Top Header
        gen_date = datetime.now(timezone.utc).strftime('%B %d, %Y')
        hdr_data = [
            [
                Paragraph("<b>PlagiScan AI</b>", h1_style),
                Paragraph(f"<b>Report Generated:</b> {gen_date}", ParagraphStyle('Rgt1', parent=subtitle_style, alignment=2))
            ],
            [
                Paragraph("Academic Content Integrity & Stylometric Evaluation", subtitle_style),
                Paragraph(f"<b>Reference ID:</b> PLAG-{analysis.id:05d}", ParagraphStyle('Rgt2', parent=subtitle_style, alignment=2))
            ]
        ]
        hdr_table = Table(hdr_data, colWidths=[330, 210])
        hdr_table.setStyle(TableStyle([
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('BOTTOMPADDING', (0,0), (-1,-1), 1),
            ('TOPPADDING', (0,0), (-1,-1), 1),
        ]))
        elements.append(hdr_table)
        elements.append(Spacer(1, 6))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=ACCENT_COLOR, spaceAfter=10))

        # 1.2 Document Metadata Grid
        meta_data = [
            [
                Paragraph("<b>Document Title:</b>", body_style),
                Paragraph(html.escape(document.filename), body_style),
                Paragraph("<b>Total Word Count:</b>", body_style),
                Paragraph(f"{document.word_count:,}", body_style)
            ],
            [
                Paragraph("<b>File Format:</b>", body_style),
                Paragraph(f".{document.file_type.upper()}", body_style),
                Paragraph("<b>Sentence Count:</b>", body_style),
                Paragraph(f"{analysis.sentence_count}", body_style)
            ],
            [
                Paragraph("<b>Reading Time:</b>", body_style),
                Paragraph(f"~{analysis.reading_time_minutes} min", body_style),
                Paragraph("<b>Lexical Diversity:</b>", body_style),
                Paragraph(f"{analysis.lexical_diversity} (TTR)", body_style)
            ]
        ]
        meta_table = Table(meta_data, colWidths=[105, 165, 115, 155])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), LIGHT_BG),
            ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
            ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ]))
        elements.append(meta_table)
        elements.append(Spacer(1, 10))

        # 1.3 Key Scorecards (Direct Database Values - Single Source of Truth)
        plag_color = colors.HexColor('#dc2626') if analysis.plagiarism_score > 25 else (colors.HexColor('#ca8a04') if analysis.plagiarism_score > 10 else colors.HexColor('#16a34a'))
        ai_color = colors.HexColor('#dc2626') if analysis.ai_likelihood_score > 60 else (colors.HexColor('#ca8a04') if analysis.ai_likelihood_score > 35 else colors.HexColor('#16a34a'))

        cards_data = [
            [
                Paragraph(f"<font color='{plag_color}'>{analysis.plagiarism_score}%</font>", card_val_style),
                Paragraph(f"<font color='{ai_color}'>{analysis.ai_likelihood_score}%</font>", card_val_style),
                Paragraph(f"<font color='#0f766e'>Grade {analysis.flesch_kincaid_grade}</font>", card_val_style)
            ],
            [
                Paragraph(f"<b>Plagiarism Similarity</b><br/>Corpus Overlap Rate", card_lbl_style),
                Paragraph(f"<b>AI Likelihood Estimate</b><br/>Risk Level: {analysis.ai_risk_level}", card_lbl_style),
                Paragraph(f"<b>Readability Index</b><br/>Ease: {analysis.flesch_reading_ease}/100", card_lbl_style)
            ]
        ]
        cards_table = Table(cards_data, colWidths=[180, 180, 180])
        cards_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.white),
            ('BOX', (0,0), (-1,-1), 1, BORDER_COLOR),
            ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
            ('TOPPADDING', (0,0), (-1,-1), 8),
            ('BOTTOMPADDING', (0,0), (-1,-1), 8),
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ]))
        elements.append(cards_table)
        elements.append(Spacer(1, 12))

        # 1.4 Executive Analysis Overview & Corpus Scope
        elements.append(Paragraph("<b>Executive Analysis Overview</b>", h2_style))
        overview_text = (
            f"Document evaluation completed for <b>{html.escape(document.filename)}</b>. "
            f"The plagiarism detection engine identified an overall textual similarity of <b>{analysis.plagiarism_score}%</b>. "
            f"Stylometric analysis estimated an AI-generated writing likelihood of <b>{analysis.ai_likelihood_score}%</b> "
            f"categorized under risk tier <b>{analysis.ai_risk_level}</b>. "
            f"Academic readability scored at <b>Grade {analysis.flesch_kincaid_grade}</b> with a Reading Ease rating of <b>{analysis.flesch_reading_ease}/100</b>."
        )
        elements.append(Paragraph(overview_text, body_style))
        elements.append(Spacer(1, 8))

        scope_box_data = [[
            Paragraph(
                "<b>Scope & Methodology Notice:</b> Plagiarism checking is strictly bounded by the locally indexed reference repository "
                "and peer documents. Zero similarity against local documents does not guarantee absence of external overlap. "
                "AI estimation uses statistical stylometrics (Perplexity, Burstiness, and transitional markers); results indicate "
                "structural probability rather than definitive proof of authorship.",
                ParagraphStyle('Notice', parent=body_style, fontSize=8, leading=11, textColor=colors.HexColor('#475569'))
            )
        ]]
        scope_table = Table(scope_box_data, colWidths=[540])
        scope_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f1f5f9')),
            ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
            ('TOPPADDING', (0,0), (-1,-1), 6),
            ('BOTTOMPADDING', (0,0), (-1,-1), 6),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
        ]))
        elements.append(scope_table)

        # Force clean page transition to Page 2
        elements.append(PageBreak())

        # =========================================================================
        # PAGE 2: SECTION ANALYSIS, CITATION CHECKING, AND MATCHING SOURCES
        # =========================================================================

        # 2.1 Section-Wise Document Analysis
        elements.append(Paragraph("<b>Section-Wise Document Analysis</b>", h2_style))
        elements.append(Paragraph("<i>Each identified structural module is evaluated independently. Section word counts reconcile with the total document word count.</i>", subtitle_style))
        elements.append(Spacer(1, 6))

        if sections:
            sec_header = [
                Paragraph("<b>Section Name</b>", body_bold),
                Paragraph("<b>Words</b>", body_bold),
                Paragraph("<b>Plagiarism %</b>", body_bold),
                Paragraph("<b>AI Likelihood %</b>", body_bold)
            ]
            sec_rows = [sec_header]
            total_sec_words = 0
            for sec in sections:
                total_sec_words += sec.word_count
                sec_rows.append([
                    Paragraph(html.escape(sec.section_name), body_style),
                    Paragraph(f"{sec.word_count:,}", body_style),
                    Paragraph(f"{sec.plagiarism_score}%", body_style),
                    Paragraph(f"{sec.ai_score}%", body_style)
                ])

            # Total Summary Row for Reconciliation
            sec_rows.append([
                Paragraph("<b>Total Reconciled Count</b>", body_bold),
                Paragraph(f"<b>{total_sec_words:,}</b>", body_bold),
                Paragraph(f"<b>{analysis.plagiarism_score}% (Overall)</b>", body_bold),
                Paragraph(f"<b>{analysis.ai_likelihood_score}% (Overall)</b>", body_bold)
            ])

            sec_table = Table(sec_rows, colWidths=[240, 80, 110, 110], repeatRows=1)
            sec_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#f1f5f9')),
                ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
                ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
                ('LINEBELOW', (0,-1), (-1,-1), 1, BORDER_COLOR),
                ('BACKGROUND', (0,-1), (-1,-1), colors.HexColor('#f8fafc')),
                ('TOPPADDING', (0,0), (-1,-1), 4),
                ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ]))
            elements.append(sec_table)
        else:
            elements.append(Paragraph("No distinct structural sections detected.", body_style))
        elements.append(Spacer(1, 10))

        # 2.2 Citation & Reference Verification
        elements.append(Paragraph("<b>Citation & Reference Verification</b>", h2_style))
        dominant_format = "IEEE Numeric / APA Detected" if analysis.citation_count > 0 else "None Detected"
        cite_data = [
            [
                Paragraph("<b>In-Text Citations Detected:</b>", body_style),
                Paragraph(str(analysis.citation_count), body_style),
                Paragraph("<b>Uncited References:</b>", body_style),
                Paragraph(str(analysis.uncited_sources_count), body_style)
            ],
            [
                Paragraph("<b>Citation Format Detected:</b>", body_style),
                Paragraph(dominant_format, body_style),
                Paragraph("<b>Bibliography Integrity:</b>", body_style),
                Paragraph("Verified" if analysis.uncited_sources_count == 0 else "Review Required", body_style)
            ]
        ]
        cite_table = Table(cite_data, colWidths=[160, 110, 160, 110])
        cite_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), LIGHT_BG),
            ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
            ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ]))
        elements.append(cite_table)
        elements.append(Spacer(1, 10))

        # 2.3 Matching Source Information
        elements.append(Paragraph("<b>Matching Sources & Reference Corpus Information</b>", h2_style))
        if matches:
            src_counts = {}
            for m in matches:
                src_counts[m.source_title] = src_counts.get(m.source_title, 0) + 1

            src_header = [
                Paragraph("<b>Matching Source Title / Type</b>", body_bold),
                Paragraph("<b>Matched Passages</b>", body_bold),
                Paragraph("<b>Max Similarity</b>", body_bold)
            ]
            src_rows = [src_header]
            for title, cnt in src_counts.items():
                max_sim = max((m.similarity_percentage for m in matches if m.source_title == title), default=0.0)
                src_rows.append([
                    Paragraph(html.escape(title), body_style),
                    Paragraph(f"{cnt} passage(s)", body_style),
                    Paragraph(f"{max_sim}%", body_style)
                ])

            src_table = Table(src_rows, colWidths=[330, 110, 100], repeatRows=1)
            src_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#f1f5f9')),
                ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
                ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
                ('TOPPADDING', (0,0), (-1,-1), 4),
                ('BOTTOMPADDING', (0,0), (-1,-1), 4),
            ]))
            elements.append(src_table)
        else:
            elements.append(Paragraph("No textual overlap detected against the available local reference corpus.", body_style))
        elements.append(Spacer(1, 10))

        # Force clean page transition to Page 3+ for Evaluated Text
        elements.append(PageBreak())

        # =========================================================================
        # REMAINING PAGES: EVALUATED DOCUMENT TEXT WITH YELLOW ERROR HIGHLIGHTS
        # =========================================================================

        elements.append(Paragraph("<b>Evaluated Document Content (Complete Text with Yellow Error Highlights)</b>", h2_style))
        elements.append(Paragraph("<i>All submitted text from the document is reproduced in full below. Suspected plagiarism matches and AI-flagged passages are highlighted in yellow.</i>", subtitle_style))
        elements.append(Spacer(1, 8))

        if document and document.raw_text:
            # Build list of error passages to highlight in yellow
            error_phrases = []
            for m in matches:
                if m.query_text and m.query_text.strip():
                    error_phrases.append(m.query_text.strip())

            for s in ai_sentences:
                if s.is_flagged and s.sentence_text and s.sentence_text.strip():
                    error_phrases.append(s.sentence_text.strip())

            # Structure full document into paragraphs
            raw = document.raw_text.replace('\r\n', '\n').replace('\r', '\n')
            lines = [l.strip() for l in raw.split('\n')]
            doc_paras = []
            cur_p = []

            for line in lines:
                if not line:
                    if cur_p:
                        doc_paras.append(" ".join(cur_p))
                        cur_p = []
                elif re.match(r'^(Abstract|\d+(?:\.\d+)*\.?\s+[A-Za-z]|References|ARTIFICIAL|Student Name|TEST NOTICE|Page \d)', line):
                    if cur_p:
                        doc_paras.append(" ".join(cur_p))
                        cur_p = []
                    doc_paras.append(line)
                elif line.startswith('•') or line.startswith('-'):
                    if cur_p:
                        doc_paras.append(" ".join(cur_p))
                        cur_p = []
                    doc_paras.append(line)
                else:
                    cur_p.append(line)
            if cur_p:
                doc_paras.append(" ".join(cur_p))

            for p in doc_paras:
                is_heading = bool(re.match(r'^(Abstract|\d+(?:\.\d+)*\.?\s+[A-Za-z]|References|ARTIFICIAL INTELLIGENCE IN EDUCATION)', p))
                p_html = html.escape(p)

                # Highlight error parts in yellow
                for err in error_phrases:
                    escaped_err = html.escape(err)
                    if escaped_err in p_html:
                        replacement = f'<font backcolor="{YELLOW_HIGHLIGHT}"><b>{escaped_err}</b></font>'
                        p_html = p_html.replace(escaped_err, replacement)
                    else:
                        # Check sentence-level substrings for multi-sentence matches
                        sub_sents = [s.strip() for s in re.split(r'(?<=[.!?])\s+', err) if len(s.strip()) > 15]
                        for sub in sub_sents:
                            esc_sub = html.escape(sub)
                            if esc_sub in p_html and f'<font backcolor="{YELLOW_HIGHLIGHT}"><b>{esc_sub}</b></font>' not in p_html:
                                p_html = p_html.replace(esc_sub, f'<font backcolor="{YELLOW_HIGHLIGHT}"><b>{esc_sub}</b></font>')

                if is_heading:
                    elements.append(Paragraph(f"<b>{p_html}</b>", h3_style))
                elif p.startswith('•') or p.startswith('-'):
                    elements.append(Paragraph(p_html, bullet_style))
                else:
                    elements.append(Paragraph(p_html, body_style))
                    elements.append(Spacer(1, 3))

        elements.append(Spacer(1, 10))

        # =========================================================================
        # FLAGGED EXCERPTS & TEXT EVIDENCE DETAILS
        # =========================================================================
        flagged_ai = [s for s in ai_sentences if s.is_flagged][:4]
        if matches or flagged_ai:
            elements.append(Paragraph("<b>Flagged Excerpts & Forensic Evidence</b>", h2_style))

            if matches:
                elements.append(Paragraph("<b>Plagiarism & Repetition Evidence:</b>", body_bold))
                for m in matches[:4]:
                    txt = (
                        f"<b>Matched against:</b> {html.escape(m.source_title)} ({m.similarity_percentage}% similarity)<br/>"
                        f"<i>\"{html.escape(m.query_text)}\"</i>"
                    )
                    elements.append(Paragraph(txt, ParagraphStyle('PlagEvidence', parent=body_style, backColor=colors.HexColor('#fef08a'), borderPadding=5, spaceAfter=5)))

            if flagged_ai:
                elements.append(Paragraph("<b>Suspected AI Stylometric Markers (Low Burstiness / Predictable Syntax):</b>", body_bold))
                for s in flagged_ai:
                    prob_pct = round(s.ai_probability * 100, 1)
                    txt = (
                        f"<b>Sentence #{s.sentence_index + 1}</b> (Estimated Probability: {prob_pct}%, Burstiness: {s.burstiness_score}, Perplexity: {s.perplexity_score})<br/>"
                        f"<i>\"{html.escape(s.sentence_text)}\"</i>"
                    )
                    elements.append(Paragraph(txt, ParagraphStyle('AIEvidence', parent=body_style, backColor=colors.HexColor('#fef08a'), borderPadding=5, spaceAfter=5)))

            elements.append(Spacer(1, 10))

        # =========================================================================
        # SMART ACADEMIC IMPROVEMENT SUGGESTIONS
        # =========================================================================
        elements.append(Paragraph("<b>Smart Academic Improvement Suggestions</b>", h2_style))
        if suggestions:
            sug_rows = []
            for s in suggestions[:5]:
                badge_color = '#dc2626' if s.severity == 'high' else ('#ca8a04' if s.severity == 'warning' else '#2563eb')
                sug_rows.append([
                    Paragraph(f"<font color='{badge_color}'><b>[{s.category.upper()}]</b></font> <b>{html.escape(s.title)}</b><br/>{html.escape(s.suggestion_text)}", body_style)
                ])
            sug_table = Table(sug_rows, colWidths=[540])
            sug_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), LIGHT_BG),
                ('BOX', (0,0), (-1,-1), 0.5, BORDER_COLOR),
                ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
                ('TOPPADDING', (0,0), (-1,-1), 5),
                ('BOTTOMPADDING', (0,0), (-1,-1), 5),
            ]))
            elements.append(sug_table)
        else:
            elements.append(Paragraph("No critical academic writing issues identified.", body_style))
        elements.append(Spacer(1, 10))

        # =========================================================================
        # METHODOLOGY, UNCERTAINTY & FINAL SUMMARY
        # =========================================================================
        elements.append(Paragraph("<b>Evaluation Methodology & Integrity Notice</b>", h2_style))
        disclaimer_text = (
            "<b>Methodology:</b> PlagiScan AI evaluates document originality using TF-IDF tokenization, "
            "sublinear frequency scaling, and pairwise cosine similarity. AI estimation employs stylometric variance "
            "indicators including vocabulary perplexity, burstiness distributions, and formulaic transition frequencies.<br/>"
            "<b>Disclaimer:</b> Plagiarism evaluation is strictly bounded by the local reference repository. "
            "AI estimation is a statistical heuristic and does not constitute definitive proof of machine authorship. "
            "Human academic review is required before taking any institutional or editorial decisions."
        )
        elements.append(Paragraph(disclaimer_text, ParagraphStyle('Disclaimer', parent=body_style, fontSize=7.5, leading=10.5, textColor=MUTED_TEXT)))

        # Build document with dynamic NumberedCanvas
        doc.build(elements, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer
